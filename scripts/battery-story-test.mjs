import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {parseHTML} from './vendor/linkedom.mjs';
const html=await readFile(new URL('../dist/index.html',import.meta.url),'utf8');
const script=await readFile(new URL('../src/battery-story.js',import.meta.url),'utf8');
const {document}=parseHTML(html);
const events={},mediaEvents={},frames=[];
const media={matches:false,addEventListener:(event,fn)=>mediaEvents[event]=fn};
const window={innerHeight:1000,scrollY:0,addEventListener:(event,fn)=>events[event]=fn};
Object.defineProperty(document.documentElement,'scrollHeight',{value:8000,configurable:true});
Object.defineProperties(document.querySelector('.hero'),{offsetTop:{value:0},offsetHeight:{value:800,configurable:true}});
Object.defineProperty(document.querySelector('.header'),'offsetHeight',{value:56});
const start=744,range=7000-start;
let id=0,checks=0;
const expect=(value,message)=>{assert.ok(value,message);checks++;};
vm.runInNewContext(script,{document,window,matchMedia:()=>media,requestAnimationFrame:fn=>{frames.push(fn);return ++id;}});
const flush=()=>{while(frames.length)frames.shift()();};
const story=document.querySelector('[data-battery-story]');
const scrollTo=y=>{window.scrollY=y;events.scroll();flush();};
const at=p=>scrollTo(start+p*range);
const value=key=>Number(story.style.getPropertyValue(key));
flush();
expect(story.dataset.stage==='0','Starts with cells at the top');
expect(!story.classList.contains('is-visible'),'Drawing is hidden on the first screen');
scrollTo(start-1);expect(!story.classList.contains('is-visible')&&story.dataset.progress==='0.0000','Drawing stays hidden until the hero clears the header');
scrollTo(start);expect(story.classList.contains('is-visible')&&story.dataset.progress==='0.0000','Assembly starts from zero just after the hero');
expect([...story.querySelectorAll('[data-cell]')].every(e=>Number(e.style.getPropertyValue('--assembled'))===0),'Initial cells are separated');
at(.25);expect([...story.querySelectorAll('[data-cell]')].every(e=>Number(e.style.getPropertyValue('--assembled'))===1),'All nine cells assemble before wiring');
at(.4);expect(value('--connected')===1&&value('--board')===0,'Connections complete before BMS');
at(.56);expect(value('--board')===1&&value('--case')===0,'BMS arrives before enclosure');
at(.77);expect(value('--case')===1&&value('--powered')===0,'Enclosure closes before power');
at(1);expect(value('--powered')===1&&value('--branded')===1,'Final state has power and branding');
const final=story.getAttribute('style');
at(.4);expect(value('--case')===0&&value('--board')===0&&story.dataset.stage==='1','Reverse scroll returns to wiring');
at(1);expect(story.getAttribute('style')===final,'Returning to bottom restores identical state');
at(1.5);expect(story.dataset.progress==='1.0000','Overscroll clamps to completed state');
at(-.2);expect(story.dataset.progress==='0.0000','Scroll before the hero boundary clamps to initial state');
expect(!story.classList.contains('is-visible'),'Returning into the hero hides the drawing');
events.scroll();events.scroll();events.scroll();expect(frames.length===1,'Rapid scrolling coalesces into one animation frame');flush();
media.matches=true;mediaEvents.change();flush();expect(story.dataset.motion==='reduced'&&value('--case')===1&&value('--branded')===1,'Reduced motion prepares a complete battery');
expect(!story.classList.contains('is-visible'),'Reduced motion also keeps the first screen clear');
at(.2);expect(value('--case')===1,'Reduced motion remains static while scrolling');
media.matches=false;mediaEvents.change();flush();expect(story.dataset.motion==='scroll'&&value('--case')===0,'Changing motion preference restores current scroll position');
window.innerHeight=2000;events.resize();flush();expect(Math.abs(Number(story.dataset.progress)-(window.scrollY-start)/(6000-start))<.001,'Resize recalculates actual page range');
Object.defineProperty(document.querySelector('.hero'),'offsetHeight',{value:1100,configurable:true});events.resize();flush();
scrollTo(1043);expect(!story.classList.contains('is-visible'),'Changed hero height updates the visibility boundary');
scrollTo(1044);expect(story.classList.contains('is-visible')&&story.dataset.progress==='0.0000','Resized hero starts assembly at its new end');
expect(story.getAttribute('aria-hidden')==='true'&&!story.querySelector('a,button,input'),'Decoration is excluded from keyboard and screen reader navigation');
// Every generated route must carry and run the same shared component.
const routes=JSON.parse(await readFile(new URL('../docs/routes.json',import.meta.url),'utf8'));
for(const route of routes){
 const file=route.path==='/'?'index.html':route.path.slice(1)+'/index.html';
 const {document:doc}=parseHTML(await readFile(new URL('../dist/'+file,import.meta.url),'utf8'));
 expect(doc.querySelectorAll('[data-battery-story]').length===1&&doc.querySelectorAll('script[src*="battery-story.js"]').length===1,route.path+': exactly one component and controller');
 if(route.path==='/')continue;
 const queue=[],listeners={},win={innerHeight:900,scrollY:0,addEventListener:(event,fn)=>listeners[event]=fn};
 Object.defineProperty(doc.documentElement,'scrollHeight',{value:3600,configurable:true});
 vm.runInNewContext(script,{document:doc,window:win,matchMedia:()=>({matches:false,addEventListener(){}}),requestAnimationFrame:fn=>{queue.push(fn);return queue.length;}});
 const flushRoute=()=>{while(queue.length)queue.shift()();};
 const component=doc.querySelector('[data-battery-story]');
 flushRoute();expect(!component.classList.contains('is-visible'),route.path+': clean initial view');
 win.scrollY=121;listeners.scroll();flushRoute();
 expect(component.classList.contains('is-visible')&&component.dataset.stage==='0',route.path+': starts without a home hero');
 win.scrollY=2700;listeners.scroll();flushRoute();
 expect(component.dataset.progress==='1.0000'&&component.dataset.stage==='4',route.path+': completes at its own footer');
 win.scrollY=0;listeners.pageshow();flushRoute();
 expect(!component.classList.contains('is-visible')&&component.dataset.progress==='0.0000',route.path+': returning to top resets it');
 // Search/filter/FAQ changes can alter the document length after initialization.
 Object.defineProperty(doc.documentElement,'scrollHeight',{value:1000,configurable:true});
 win.scrollY=100;listeners.resize();flushRoute();
 expect(component.dataset.progress==='1.0000',route.path+': a shortened page still reaches the final stage');
}
const report={checks,failures:[],routes:routes.length,coverage:['shared component on all routes','inner-page activation','short pages and dynamic height','hero visibility boundary','responsive hero height','assembly order','reverse scroll','restoration','overscroll','animation frame coalescing','reduced motion','resize','decorative accessibility']};
await writeFile(new URL('../checks/battery-story-report.json',import.meta.url),JSON.stringify(report,null,2));
console.log(`Battery story: ${checks} checks passed.`);
